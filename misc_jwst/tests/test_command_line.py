# Helpers (no faking of behavior -- just test plumbing)

@contextlib.contextmanager
def working_directory(path):
    """Run a block of code with the CWD temporarily changed, so that the
    PDFs a couple of these functions write don't land in the repo root.
    This doesn't fake any I/O -- the files are still really written, just
    to a temp directory.
    """
    prev = os.getcwd()
    os.chdir(path)
    try:
        yield
    finally:
        os.chdir(prev)


@contextlib.contextmanager
def argv(args):
    """Temporarily replace sys.argv, e.g. to drive jwstops_main()."""
    prev = sys.argv
    sys.argv = args
    try:
        yield
    finally:
        sys.argv = prev


