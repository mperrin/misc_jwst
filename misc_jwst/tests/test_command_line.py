    """A real, recent JWST visit ID pulled live from the engineering DB.

    Skips dependent tests if the DB is unreachable or if there's simply
    been no observatory activity in the lookback window.
    """
    now = astropy.time.Time.now()
    try:
        log = cl.engdb.get_ictm_event_log(startdate=now - 7 * u.day)
        visit_table = cl.engdb.visit_start_end_times(log, verbose=False, return_table=True)
    except Exception as exc:  # pragma: no cover - depends on live system
        pytest.skip(f"Could not reach engdb to find a sample visit: {exc}")

    if len(visit_table) == 0:
        pytest.skip("No visits found in the last 7 days to use as a test input")

    return str(visit_table[1]["visitid"])


